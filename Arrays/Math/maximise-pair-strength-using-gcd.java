import java.io.*;
import java.util.*;

class PairStrength {
    public long maximise(int[] nums) {
        long ans = Long.MIN_VALUE;
        int n=nums.length;
        for(int i=0; i<n; i++) {
            for(int j=i+1; j<n; j++) {
                int gcd = findGCD(nums[i], nums[j]);
                long val = (long) (nums[i] * nums[j]);
                long num =  (long) (gcd * gcd);
                ans = Math.max(val/num, ans);
            }
        }
        return ans;
    }

    public int findGCD(int a, int b) {
        while (b != 0) {
            int temp = b;
            b = a % b;
            a = temp;
        } 
        return a;
    }
}

